import {build} from 'esbuild';
import assert from 'node:assert/strict';
await build({entryPoints:['src/main/unionComposition.ts'],outfile:'tests/.discovery/union.mjs',bundle:true,platform:'node',format:'esm'});
const {parseUnionComposition,unionWeight,enrichUnion}=await import('./.discovery/union.mjs');
const product={id:'LU0115904467',isin:'LU0115904467',productUrl:'https://www.union-investment.de/fonds/test',breakdowns:{}};
const row=(label,valueNumeric,value)=>({label,valueNumeric,value});
const list=(headline,rows)=>({headline,listData:[{date:'30.09.2026',list:rows}]});
const data={header:{masterData:[{label:'ISIN:',text:product.isin}]},body:{pages:[{title:'Zusammensetzung',sections:[{headline:'Fondsstruktur nach Ländern',items:[{chart:{type:'world-map-chart',chartDate:'Stand: 30.09.2026',data:[{name:'Taiwan',value:22.58},{name:'Indien',value:9.63}]}}]},{items:[list('Die größten Aktienwerte',[row('Aktie A',9.4916,'9,49 %'),row('Aktie B',7.9497,'7,95 %')]),list('Fondsstruktur nach Branchen',[row('Technologie',0.378927,'37,89 %'),row('Klein',0.00003,'0,00 %')])]}]}]}};
const result=parseUnionComposition(data,product);
assert.equal(result.breakdowns.countries.rows[0].weight,22.58);
assert.equal(result.breakdowns.holdings.rows[0].weight,9.4916);
assert.ok(Math.abs(result.breakdowns.sectors.rows[0].weight-37.8927)<1e-10);
assert.equal(result.breakdowns.sectors.rows[1].weight,0.003);
assert.equal(result.breakdowns.holdings.asOf,'2026-09-30');
assert.equal(result.breakdowns.holdings.rows[0].isin,undefined);
assert.ok(result.breakdowns.holdings.rows.reduce((s,r)=>s+r.weight,0)<18);
assert.equal(result.breakdowns.holdings.sourceUrl,product.productUrl);
assert.throws(()=>parseUnionComposition(data,{...product,isin:'DE0008491051'}));
assert.throws(()=>unionWeight(row('Mismatch',25,'12,00 %')));
assert.throws(()=>unionWeight(row('Ambiguous',0.00003,'0,00 %')));
assert.equal(unionWeight(row('Percentage',9.4916,'9,49 %')),9.4916);
assert.equal(unionWeight(row('Fraction',0.25,'25,00 %')),25);
const bad=structuredClone(data);bad.body.pages[0].sections[1].items[0].listData[0].date='unknown';
assert.equal(parseUnionComposition(bad,product).breakdowns.holdings,undefined);
const inconsistent=structuredClone(data);inconsistent.body.pages[0].sections[1].items[1].listData[0].list[1]=row('Wrong unit',20,'20,00 %');
assert.equal(parseUnionComposition(inconsistent,product).breakdowns.sectors,undefined);
const preserved=await enrichUnion(result,'',async()=>{throw Error('Offline')});
assert.deepEqual(preserved.breakdowns,result.breakdowns);
assert.equal(preserved.isin,product.isin);
console.log('Union composition: identity, partial coverage, dates, percentage/fraction units, tiny weights, inconsistent units and outage preservation passed.');
